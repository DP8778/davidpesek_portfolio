// Production browser verification with deterministic Prague time; no external messages or calls.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const url = process.env.DIGITAL_CALL_URL || 'http://localhost:4102';
(async () => {
 const browser = await chromium.launch();
 try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, timezoneId: 'Europe/Prague', locale: 'cs-CZ' });
  const page = await context.newPage();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  page.setDefaultTimeout(12000);
  await page.clock.install({ time: new Date('2026-10-12T13:00:00+02:00') });
  await page.goto(url, { waitUntil: 'domcontentloaded' });
  const anna = () => page.evaluate(() => JSON.parse(localStorage.getItem('obvolavani-portfolio-demo-v2')).contacts.find(c => c.id === 'demo-1'));
  const attempts = c => c.history.filter(e => e.type === 'call_attempt').length;
  await page.getByText('Anna Novotná', { exact: true }).click();
  const initial = await anna();
  await page.getByRole('button', { name: 'Upravit termín', exact: true }).click();
  await page.locator('input[type=datetime-local]').fill('2026-10-12T15:30');
  await page.getByRole('button', { name: 'Uložit termín', exact: true }).click();
  await page.getByText('Termín byl nastaven v demu', { exact: true }).waitFor();
  const scheduled = await anna();
  assert.equal(attempts(scheduled), attempts(initial)); assert.equal(scheduled.status, initial.status);
  assert.equal(scheduled.nextActivity.dueAt, Date.parse('2026-10-12T15:30:00+02:00'));
  await page.getByRole('button', { name: 'Zůstat v detailu', exact: true }).click();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Proces', exact: true }).click();
  assert.equal(attempts(await anna()), attempts(initial));
  await page.getByRole('button', { name: 'K řešení', exact: true }).click();
  await page.getByText('Anna Novotná', { exact: true }).click();
  await page.clock.setSystemTime(new Date('2026-10-12T15:35:00+02:00')); await page.clock.runFor(16000);
  const openOutcome = () => page.getByRole('button', { name: 'Zaznamenat výsledek hovoru', exact: true }).click();
  await openOutcome();
  await page.getByText('Zvolit vlastní termín', { exact: true }).click();
  await page.locator('input[type=datetime-local]').fill('2026-10-12T15:00');
  await page.getByRole('button', { name: 'Uložit výsledek', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'budoucí termín' }).waitFor();
  assert.equal(attempts(await anna()), attempts(initial));
  await page.getByRole('button', { name: 'Zrušit', exact: true }).click();
  assert.equal(attempts(await anna()), attempts(initial));
  await openOutcome();
  await page.getByText('Zvolit vlastní termín', { exact: true }).click();
  await page.locator('input[type=datetime-local]').fill('2026-10-13T16:00');
  await page.getByRole('button', { name: 'Uložit výsledek', exact: true }).click();
  await page.getByRole('button', { name: 'Zpět do fronty', exact: true }).waitFor();
  const accepted = await anna();
  assert.equal(attempts(accepted), attempts(initial) + 1); assert.equal(accepted.status, 'call_later');
  assert.equal(accepted.nextActivity.dueAt, Date.parse('2026-10-13T16:00:00+02:00'));
  await page.getByRole('button', { name: 'Zpět do fronty', exact: true }).click();
  await page.reload(); await page.getByText('Anna Novotná', { exact: true }).waitFor();
  assert.deepEqual(await anna(), accepted);
  await page.getByRole('button', { name: 'Obnovit demo', exact: true }).click();
  const resetDialog = page.getByRole('dialog');
  await resetDialog.getByRole('button', { name: /Obnovit demo|Obnovit výchozí|Ano, obnovit/ }).click();
  await page.getByText('Anna Novotná', { exact: true }).waitFor();
  assert.equal(attempts(await anna()), attempts(initial));
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ status: 'passed', url, timezone: 'Europe/Prague', checks: ['open and process view add no attempt', 'manual schedule preserves status and attempt count', 'expired result rejected without false success', 'cancel preserves state', 'accepted result adds exactly one attempt', 'chosen next activity', 'queue return', 'storage after refresh', 'reset', 'buttons work without drag-and-drop'], initialAttempts: attempts(initial), acceptedAttempts: attempts(accepted) }, null, 2));
 } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
